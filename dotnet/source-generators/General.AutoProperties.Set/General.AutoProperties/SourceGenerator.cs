using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Reflection;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using Plate.SCG.Shared.Abstractions;

namespace Plate.SCG.General.AutoProperties;

[Generator(LanguageNames.CSharp)]
public class SourceGenerator : IIncrementalGenerator
{
    private const string AutoProperty = "AutoProperty";
    private const string AutoPropertyAttribute = "AutoPropertyAttribute";
    private const string GenerateProperty = "GenerateProperty";
    private const string GeneratePropertyAttribute = "GeneratePropertyAttribute";
    private const string SkipProperty = "SkipProperty";
    private const string SkipPropertyAttribute = "SkipPropertyAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var typeSymbols = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (syntaxNode, cancellationToken) =>
                    Utility.PredicateAsync(syntaxNode, AutoProperty, AutoPropertyAttribute, cancellationToken),
                Utility.TransformAsync)
            .Where(static typeSymbol => typeSymbol is not null)
            .Collect();

        context.RegisterSourceOutput(typeSymbols, GenerateCode!);
    }

    private static void GenerateCode(
        SourceProductionContext context,
        ImmutableArray<ITypeSymbol> typeSymbols)
    {
        if (typeSymbols.IsDefaultOrEmpty)
        {
            return;
        }

        var executingAssemblyName = Assembly.GetExecutingAssembly().GetName();
        foreach (var typeSymbol in typeSymbols)
        {
            var ns = typeSymbol.ContainingNamespace.ToDisplayString();
            var fileName = $"{ns}.{typeSymbol.Name}.AutoProperties.g.cs";
            context.AddSource(fileName, GenerateCode(executingAssemblyName, fileName, typeSymbol));
        }
    }

    private static string GenerateCode(
        AssemblyName executingAssemblyName,
        string fileName,
        ITypeSymbol typeSymbol)
    {
        var assemblyName = $"{executingAssemblyName.Name}.{nameof(SourceGenerator)}";
        var assemblyVersion = $"{executingAssemblyName.Version}";
        var namespaceName = typeSymbol.ContainingNamespace.ToDisplayString();
        var typeDeclarationLine = Utility.CreateTypeDeclarationLine(typeSymbol);
        var codeGenAttributes = Utility.CreateCodeGenAttributes(assemblyName, assemblyVersion);
        var indentedAttributes = Utility.Indent(codeGenAttributes, 4);

        var autoPropertyConfig = GetAutoPropertyConfiguration(typeSymbol);
        var fieldsToGenerate = GetFieldsToGenerateProperties(typeSymbol, autoPropertyConfig);

        var properties = GenerateProperties(fieldsToGenerate, autoPropertyConfig);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine($"// {fileName}");
        sb.AppendLine();
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine($"namespace {namespaceName};");
        sb.AppendLine();
        sb.AppendLine(typeDeclarationLine);
        sb.AppendLine("{");
        sb.Append(indentedAttributes);

        foreach (var property in properties)
        {
            sb.AppendLine(property);
        }

        sb.AppendLine("}");

        return sb.ToString();
    }

    private static AutoPropertyConfiguration GetAutoPropertyConfiguration(ITypeSymbol typeSymbol)
    {
        var config = new AutoPropertyConfiguration();

        var autoPropertyAttribute = typeSymbol.GetAttributes()
            .FirstOrDefault(a => a.AttributeClass?.Name == AutoProperty ||
                               a.AttributeClass?.Name == AutoPropertyAttribute);

        if (autoPropertyAttribute != null)
        {
            // Extract configuration from attribute arguments
            foreach (var namedArg in autoPropertyAttribute.NamedArguments)
            {
                switch (namedArg.Key)
                {
                    case nameof(config.DefaultAccessibility):
                        config.DefaultAccessibility = (PropertyAccessibility)(int)namedArg.Value.Value!;
                        break;
                    case nameof(config.DefaultPropertyKind):
                        config.DefaultPropertyKind = (PropertyKind)(int)namedArg.Value.Value!;
                        break;
                    case nameof(config.GenerateForAllFields):
                        config.GenerateForAllFields = (bool)namedArg.Value.Value!;
                        break;
                    case nameof(config.FieldPrefix):
                        config.FieldPrefix = (string)namedArg.Value.Value!;
                        break;
                }
            }
        }

        return config;
    }

    private static List<FieldPropertyInfo> GetFieldsToGenerateProperties(
        ITypeSymbol typeSymbol,
        AutoPropertyConfiguration config)
    {
        var privateFields = GetPrivateFields(typeSymbol);
        var fieldsToGenerate = new List<FieldPropertyInfo>();

        foreach (var field in privateFields)
        {
            var generatePropertyAttribute = field.GetAttributes()
                .FirstOrDefault(a => a.AttributeClass?.Name == GenerateProperty ||
                                   a.AttributeClass?.Name == GeneratePropertyAttribute);

            var skipPropertyAttribute = field.GetAttributes()
                .FirstOrDefault(a => a.AttributeClass?.Name == SkipProperty ||
                                   a.AttributeClass?.Name == SkipPropertyAttribute);

            // Skip if explicitly marked to skip
            if (skipPropertyAttribute != null)
                continue;

            // Generate if explicitly marked or if generating for all fields
            if (generatePropertyAttribute != null || config.GenerateForAllFields)
            {
                var fieldInfo = new FieldPropertyInfo
                {
                    Field = field,
                    PropertyName = GetPropertyName(field, generatePropertyAttribute, config),
                    Accessibility = GetPropertyAccessibility(generatePropertyAttribute, config),
                    PropertyKind = GetPropertyKind(generatePropertyAttribute, config)
                };

                fieldsToGenerate.Add(fieldInfo);
            }
        }

        return fieldsToGenerate;
    }

    private static string GetPropertyName(
        IFieldSymbol field,
        AttributeData? generatePropertyAttribute,
        AutoPropertyConfiguration config)
    {
        // Check if property name is explicitly specified
        if (generatePropertyAttribute != null)
        {
            var propertyNameArg = generatePropertyAttribute.NamedArguments
                .FirstOrDefault(arg => arg.Key == "PropertyName");

            if (propertyNameArg.Value.Value is string explicitName && !string.IsNullOrWhiteSpace(explicitName))
            {
                return explicitName;
            }
        }

        // Generate from field name
        return FieldNameToPropertyName(field.Name, config.FieldPrefix);
    }

    private static PropertyAccessibility GetPropertyAccessibility(
        AttributeData? generatePropertyAttribute,
        AutoPropertyConfiguration config)
    {
        if (generatePropertyAttribute != null)
        {
            var accessibilityArg = generatePropertyAttribute.NamedArguments
                .FirstOrDefault(arg => arg.Key == "Accessibility");

            if (accessibilityArg.Value.Value != null)
            {
                return (PropertyAccessibility)(int)accessibilityArg.Value.Value;
            }
        }

        return config.DefaultAccessibility;
    }

    private static PropertyKind GetPropertyKind(
        AttributeData? generatePropertyAttribute,
        AutoPropertyConfiguration config)
    {
        if (generatePropertyAttribute != null)
        {
            var propertyKindArg = generatePropertyAttribute.NamedArguments
                .FirstOrDefault(arg => arg.Key == "PropertyKind");

            if (propertyKindArg.Value.Value != null)
            {
                return (PropertyKind)(int)propertyKindArg.Value.Value;
            }
        }

        return config.DefaultPropertyKind;
    }

    private static List<string> GenerateProperties(
        List<FieldPropertyInfo> fieldsToGenerate,
        AutoPropertyConfiguration config)
    {
        var properties = new List<string>();

        foreach (var fieldInfo in fieldsToGenerate)
        {
            var property = GenerateProperty(fieldInfo);
            properties.Add(property);
        }

        return properties;
    }

    private static string GenerateProperty(FieldPropertyInfo fieldInfo)
    {
        var accessibilityModifier = GetAccessibilityModifier(fieldInfo.Accessibility);
        var fieldName = fieldInfo.Field.Name;
        var propertyName = fieldInfo.PropertyName;
        var fieldType = fieldInfo.Field.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        var propertyCode = fieldInfo.PropertyKind switch
        {
            PropertyKind.GetterOnly => GenerateGetterOnlyProperty(accessibilityModifier, fieldType, propertyName, fieldName),
            PropertyKind.GetterPrivateSetter => GenerateGetterPrivateSetterProperty(accessibilityModifier, fieldType, propertyName, fieldName),
            PropertyKind.GetterProtectedSetter => GenerateGetterProtectedSetterProperty(accessibilityModifier, fieldType, propertyName, fieldName),
            PropertyKind.GetterInternalSetter => GenerateGetterInternalSetterProperty(accessibilityModifier, fieldType, propertyName, fieldName),
            _ => GenerateGetterSetterProperty(accessibilityModifier, fieldType, propertyName, fieldName)
        };

        return Utility.Indent(propertyCode, 4);
    }

    private static string GetAccessibilityModifier(PropertyAccessibility accessibility)
    {
        return accessibility switch
        {
            PropertyAccessibility.Public => "public",
            PropertyAccessibility.Internal => "internal",
            PropertyAccessibility.Protected => "protected",
            PropertyAccessibility.Private => "private",
            _ => "public"
        };
    }

    private static string GenerateGetterSetterProperty(string accessibility, string type, string propertyName, string fieldName)
    {
        return $@"{accessibility} {type} {propertyName}
{{
    get => {fieldName};
    set => {fieldName} = value;
}}";
    }

    private static string GenerateGetterOnlyProperty(string accessibility, string type, string propertyName, string fieldName)
    {
        return $@"{accessibility} {type} {propertyName}
{{
    get => {fieldName};
}}";
    }

    private static string GenerateGetterPrivateSetterProperty(string accessibility, string type, string propertyName, string fieldName)
    {
        return $@"{accessibility} {type} {propertyName}
{{
    get => {fieldName};
    private set => {fieldName} = value;
}}";
    }

    private static string GenerateGetterProtectedSetterProperty(string accessibility, string type, string propertyName, string fieldName)
    {
        return $@"{accessibility} {type} {propertyName}
{{
    get => {fieldName};
    protected set => {fieldName} = value;
}}";
    }

    private static string GenerateGetterInternalSetterProperty(string accessibility, string type, string propertyName, string fieldName)
    {
        return $@"{accessibility} {type} {propertyName}
{{
    get => {fieldName};
    internal set => {fieldName} = value;
}}";
    }

    private class AutoPropertyConfiguration
    {
        public PropertyAccessibility DefaultAccessibility { get; set; } = PropertyAccessibility.Public;
        public PropertyKind DefaultPropertyKind { get; set; } = PropertyKind.GetterSetter;
        public bool GenerateForAllFields { get; set; } = false;
        public string FieldPrefix { get; set; } = "_";
    }

    private class FieldPropertyInfo
    {
        public IFieldSymbol Field { get; set; } = null!;
        public string PropertyName { get; set; } = string.Empty;
        public PropertyAccessibility Accessibility { get; set; }
        public PropertyKind PropertyKind { get; set; }
    }

    // These enums mirror the ones in the attributes package
    private enum PropertyAccessibility
    {
        Public,
        Internal,
        Protected,
        Private
    }

    private enum PropertyKind
    {
        GetterSetter,
        GetterOnly,
        GetterPrivateSetter,
        GetterProtectedSetter,
        GetterInternalSetter
    }

    // Helper methods for field processing
    private static List<IFieldSymbol> GetPrivateFields(ITypeSymbol typeSymbol)
    {
        return typeSymbol.GetMembers()
            .OfType<IFieldSymbol>()
            .Where(f => f.DeclaredAccessibility == Accessibility.Private)
            .Where(f => !f.IsStatic)
            .Where(f => !f.IsConst)
            .Where(f => !f.IsReadOnly || f.Type.IsReferenceType) // Allow readonly reference types
            .ToList();
    }

    private static string FieldNameToPropertyName(string fieldName, string fieldPrefix = "_")
    {
        if (string.IsNullOrEmpty(fieldName))
            return fieldName;

        var propertyName = fieldName;

        // Remove prefix if it exists
        if (!string.IsNullOrEmpty(fieldPrefix) && propertyName.StartsWith(fieldPrefix))
        {
            propertyName = propertyName.Substring(fieldPrefix.Length);
        }

        // Convert to Pascal case
        if (propertyName.Length > 0)
        {
            propertyName = char.ToUpperInvariant(propertyName[0]) + propertyName.Substring(1);
        }

        return propertyName;
    }
}
