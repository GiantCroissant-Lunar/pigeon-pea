namespace PigeonPea.Perception.Enums;

/// <summary>
/// Represents the emotional state of the AI agent.
/// </summary>
public enum EmotionalState
{
    /// <summary>
    /// Default neutral state.
    /// </summary>
    Neutral = 0,

    /// <summary>
    /// Confident and in control.
    /// </summary>
    Confident = 1,

    /// <summary>
    /// Afraid or nervous.
    /// </summary>
    Afraid = 2,

    /// <summary>
    /// Angry or aggressive.
    /// </summary>
    Angry = 3,

    /// <summary>
    /// Curious about surroundings.
    /// </summary>
    Curious = 4,

    /// <summary>
    /// Confused or uncertain.
    /// </summary>
    Confused = 5
}
