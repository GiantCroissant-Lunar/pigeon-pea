namespace PigeonPea.Perception.Enums;

/// <summary>
/// Represents the type of memory stored by the AI agent.
/// </summary>
public enum MemoryType
{
    /// <summary>
    /// Short-term memory (e.g., recent events within the current engagement).
    /// </summary>
    ShortTerm = 0,

    /// <summary>
    /// Long-term memory (e.g., persistent knowledge about the world).
    /// </summary>
    LongTerm = 1
}
